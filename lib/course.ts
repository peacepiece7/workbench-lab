export function evaluate(lesson: Lesson, values: number[]) {
  if (
    values.length !== lesson.controls.length ||
    values.some(
      (v, i) =>
        !Number.isInteger(v) || v < 0 || v >= lesson.controls[i].options.length,
    )
  )
    throw new Error('유효하지 않은 설계 변수입니다.');
  return lesson.tests.map((t) => ({
    pass: t.requires.every(
      (allowed, i) => allowed.length === 0 || allowed.includes(values[i]),
    ),
  }));
}
